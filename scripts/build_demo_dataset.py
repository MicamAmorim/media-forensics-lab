from __future__ import annotations

import shutil
from pathlib import Path

import mf_lab  # activates Windows/OpenCV Unicode compatibility guards
import cv2
import numpy as np
from PIL import Image
from skimage import data

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "dataset" / "demo"
FIX = ROOT / "dataset" / "fixtures"
GT = OUT / "ground_truth.json"


def save_rgb(path: Path, arr: np.ndarray, quality: int = 95) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    Image.fromarray(arr.astype(np.uint8)).save(path, quality=quality)


def _write_png_unicode(path: Path, arr: np.ndarray) -> None:
    ok, buf = cv2.imencode(".png", arr)
    if not ok:
        raise RuntimeError(f"could not encode {path}")
    buf.tofile(path)


def _make_face_replacement(base_rgb: np.ndarray, donor_path: Path):
    base_bgr = cv2.cvtColor(base_rgb, cv2.COLOR_RGB2BGR)
    donor = cv2.imdecode(np.fromfile(donor_path, dtype=np.uint8), cv2.IMREAD_COLOR)
    if donor is None:
        raise RuntimeError(f"could not decode face donor fixture: {donor_path}")

    cascade = cv2.CascadeClassifier(cv2.data.haarcascades + "haarcascade_frontalface_default.xml")
    fb = cascade.detectMultiScale(
        cv2.cvtColor(base_bgr, cv2.COLOR_BGR2GRAY), 1.1, 5, minSize=(50, 50)
    )
    fd = cascade.detectMultiScale(
        cv2.cvtColor(donor, cv2.COLOR_BGR2GRAY), 1.1, 5, minSize=(30, 30)
    )
    if len(fb) == 0 or len(fd) == 0:
        raise RuntimeError("face fixture generation requires detectable faces")

    x, y, w, h = [int(v) for v in max(fb, key=lambda z: z[2] * z[3])]
    dx, dy, dw, dh = [int(v) for v in max(fd, key=lambda z: z[2] * z[3])]
    face = cv2.resize(
        donor[dy : dy + dh, dx : dx + dw], (w, h), interpolation=cv2.INTER_CUBIC
    )
    mask = np.zeros((h, w), np.uint8)
    cv2.ellipse(
        mask,
        (w // 2, h // 2),
        (int(w * 0.45), int(h * 0.48)),
        0,
        0,
        360,
        255,
        -1,
    )
    blend = cv2.seamlessClone(
        face, base_bgr, mask, (x + w // 2, y + h // 2), cv2.NORMAL_CLONE
    )
    fullmask = np.zeros(base_bgr.shape[:2], np.uint8)
    fullmask[y : y + h, x : x + w] = mask
    return cv2.cvtColor(blend, cv2.COLOR_BGR2RGB), fullmask, [x, y, w, h]


def _reset_generated_subdirs() -> None:
    """Rebuild media while preserving the canonical GT oracle.

    `ground_truth.json` is intentionally not generated by this script. CI uses
    it as an independent regression contract, so code that builds fixtures must
    never silently rewrite the expected answers it is later evaluated against.
    """
    if not GT.is_file():
        raise RuntimeError(
            f"canonical ground truth is missing: {GT}. Restore it from version control."
        )

    OUT.mkdir(parents=True, exist_ok=True)
    for name in ("images", "videos", "masks"):
        path = OUT / name
        if path.exists():
            shutil.rmtree(path)
        path.mkdir(parents=True, exist_ok=True)


def main() -> None:
    _reset_generated_subdirs()

    astronaut = data.astronaut()
    coffee = cv2.resize(data.coffee(), (astronaut.shape[1], astronaut.shape[0]))

    save_rgb(OUT / "images" / "img_001_pristine.jpg", astronaut, 95)

    copy_move = astronaut.copy()
    patch = copy_move[90:190, 70:170].copy()
    copy_move[330:430, 300:400] = patch
    copy_mask = np.zeros(astronaut.shape[:2], np.uint8)
    copy_mask[330:430, 300:400] = 255
    save_rgb(OUT / "images" / "img_002_copy_move.jpg", copy_move, 92)
    _write_png_unicode(OUT / "masks" / "img_002_copy_move_mask.png", copy_mask)

    splice = astronaut.copy()
    donor = cv2.GaussianBlur(coffee[150:280, 170:330], (3, 3), 0)
    splice[260:390, 40:200] = donor
    splice_mask = np.zeros(astronaut.shape[:2], np.uint8)
    splice_mask[260:390, 40:200] = 255
    save_rgb(OUT / "images" / "img_003_splice.jpg", splice, 90)
    _write_png_unicode(OUT / "masks" / "img_003_splice_mask.png", splice_mask)

    tmp = OUT / "images" / "_tmp.jpg"
    save_rgb(tmp, astronaut, 70)
    with Image.open(tmp) as im:
        im.save(OUT / "images" / "img_004_double_jpeg.jpg", quality=92)
    tmp.unlink()

    h, w = astronaut.shape[:2]
    matrix = cv2.getRotationMatrix2D((w / 2, h / 2), 3.2, 1.08)
    resampled = cv2.warpAffine(
        astronaut, matrix, (w, h), borderMode=cv2.BORDER_REFLECT
    )
    save_rgb(OUT / "images" / "img_005_resampled.jpg", resampled, 94)

    bgr = cv2.cvtColor(astronaut, cv2.COLOR_RGB2BGR)
    inpaint_mask = np.zeros((h, w), np.uint8)
    cv2.circle(inpaint_mask, (260, 250), 35, 255, -1)
    inpainted = cv2.inpaint(bgr, inpaint_mask, 5, cv2.INPAINT_TELEA)
    save_rgb(
        OUT / "images" / "img_006_inpainted.jpg",
        cv2.cvtColor(inpainted, cv2.COLOR_BGR2RGB),
        93,
    )
    _write_png_unicode(OUT / "masks" / "img_006_inpainted_mask.png", inpaint_mask)

    face_rgb, face_mask, _face_bbox = _make_face_replacement(
        astronaut, FIX / "face_donor_ai.jpg"
    )
    save_rgb(OUT / "images" / "img_007_deepfake_face.jpg", face_rgb, 94)
    _write_png_unicode(OUT / "masks" / "img_007_deepfake_face_mask.png", face_mask)

    with Image.open(FIX / "ai_generated_fixture.jpg") as ai_src:
        ai_src.convert("RGB").resize(
            (512, 512), Image.Resampling.LANCZOS
        ).save(OUT / "images" / "img_008_ai_generated.png")

    frames = []
    for i in range(72):
        frame = astronaut.copy()
        x = 20 + (i * 5) % 400
        cv2.circle(frame, (x, 460), 18, (255, 255, 255), -1)
        frames.append(cv2.cvtColor(frame, cv2.COLOR_RGB2BGR))

    def write_video(name: str, sequence: list[np.ndarray]) -> None:
        path = OUT / "videos" / name
        writer = cv2.VideoWriter(
            str(path), cv2.VideoWriter_fourcc(*"mp4v"), 24, (w, h)
        )
        if not writer.isOpened():
            raise RuntimeError(f"could not create demo video: {path}")
        for frame in sequence:
            writer.write(frame)
        writer.release()

    write_video("vid_001_pristine.mp4", frames)
    duplicated = frames[:36] + [frames[35]] * 5 + frames[36:]
    write_video("vid_002_duplicated_frames.mp4", duplicated)
    deleted = frames[:30] + frames[40:]
    write_video("vid_003_deleted_segment.mp4", deleted)

    overlay = []
    for i, frame in enumerate(frames):
        edited = frame.copy()
        if 25 <= i < 50:
            cv2.rectangle(edited, (330, 60), (500, 150), (0, 0, 0), -1)
            cv2.putText(
                edited,
                "EDIT",
                (350, 120),
                cv2.FONT_HERSHEY_SIMPLEX,
                1.5,
                (255, 255, 255),
                3,
            )
        overlay.append(edited)
    write_video("vid_004_overlay_edit.mp4", overlay)

    print(OUT)


if __name__ == "__main__":
    main()
